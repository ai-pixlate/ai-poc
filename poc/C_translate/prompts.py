# LLM-as-judge — 블라인드 분야별 채점 (PLAN.md 18번)
#
# 두 번 바뀌었다.
#   v1  5점 척도 4축 → 2·3·4종 모두 격차 0.05점. 천장 효과로 변별 실패
#   v2  결함 플래그  → 천장은 없앴으나 **자기 채점 편향을 막지 못했다.**
#                     실측 — claude judge가 자기 벤더에 관대(8건 vs 평균 13.2건)
#   v3  **블라인드 분야별 채점** (현행)
#
# 핵심 설계 3가지
#   ① 블라인드 — 어떤 모델의 번역인지 알려주지 않는다. 편향을 측정이 아니라 **차단**한다.
#   ② 토큰량·시간을 주지 않는다 — 실측값이 이미 있고, 출력 토큰 수가 모델을 식별하는
#      지문이 되어 블라인드를 깬다(qwen 53,358 vs gemini 7,238).
#   ③ **평균을 LLM에게 시키지 않는다.** 분야별 점수만 받고 평균·가중·순위는 전부 로컬이다.
#      LLM이 평균을 내면 심각한 결함 1건이 0.06점으로 묻힌다.
# ─────────────────────────────────────────────────────────────

# 채점 분야 3개. **토큰량·시간은 여기에 없다** — judge에게 넘기지 않기로 했으므로
# LLM이 채점할 수 없다. 실측값이 이미 있으므로 로컬 집계로만 다룬다.
JUDGE_AXES: dict[str, str] = {
    "instruction":   "규제 매핑 표를 문맥에 맞게 적용했는가. "
                     "**적용해야 할 자리에 적용했는가와, 적용하면 안 되는 자리에 "
                     "적용하지 않았는가를 함께 본다. 과잉 적용도 감점한다**",
    "hallucination": "원문에 없는 정보를 지어내지 않았는가. 숫자·성분명·인증명이 정확한가",
    "quality":       "영어로 자연스럽고 현지 소비자에게 통하는가. 어투가 원문과 맞는가",
}

JUDGE_SYSTEM = """당신은 한국 화장품 상세페이지 번역을 검수하는 심사자다.
원문(한국어)과 번역문({target_lang})을 받아 아래 3개 분야에 각각 1~10점을 매긴다.

**어떤 모델이 번역했는지 알려주지 않는다. 번역문만 보고 판단하라.**
**분야별 점수만 매겨라. 평균을 내지 마라 — 집계는 다른 곳에서 한다.**

[점수 기준 — 3개 분야 공통]

| 점수 | 뜻 |
|---|---|
| 10 | 흠잡을 데 없다 |
| 7 | 사소한 결함이 있으나 의미는 온전하다 |
| 4 | 의미가 훼손됐다 |
| 1 | 그대로 쓸 수 없다 |

중간값(9, 8, 6 …)을 써도 된다.

[채점 분야]

| 분야 | 무엇을 보는가 |
|---|---|
{axis_table}

[규제 표 적용 판정 — `compliance`]

원문에 규제 매핑 표의 표현이 있다면, **대체 여부가 그 자리에 맞았는지** 답한다.
대체했는지 안 했는지가 아니라 **그 판단이 옳았는지**를 본다.

- `정당` — 판단이 맞다. 둘 중 하나다.
    · 브랜드가 효능을 주장하는 자리여서 **대체했다**
    · 바꾸면 안 되는 자리여서 **유지했다** — 효능을 부인·고지하는 문장, 제3자 인용,
      제품명·라인명, 법령·고시 인용, 수상·부문명 등
- `부당` — 판단이 틀렸다. **양방향 모두 여기에 해당한다.**
    · **미적용** — 바꿔야 하는 자리인데 유지했다
    · **과잉 적용** — 바꾸면 안 되는 자리인데 대체했다.
      제품명·인용문·법령명이 바뀌면 **원문이 가리키던 대상이 달라진다.**
      받지 않은 상, 존재하지 않는 법령, 하지 않은 말이 된다. 미적용보다 위험할 수 있다
- `해당없음` — 규제 표의 표현이 원문에 없다

**규제 표 자체가 문제인 경우도 `정당`으로 보고 `reason`에 적어라.**
  - 대체표현이 원 표현의 직역과 구별되지 않는다 (예: 재생 → renewing)
  - 서로 다른 금지표현이 같은 대체표현으로 수렴한다
  - 대체하면 원문의 숫자·고유명사가 사라진다

[감점하지 말아야 할 것]
1. 규제 표대로 바꾼 것. 지시받은 대로 한 것이다
2. 브랜드명·제품명을 원표기로 남긴 것
3. 한국어와 영어의 자연스러운 어순·표현 차이

{regulation_block}

`reason`은 **점수를 깎았거나 `compliance`가 `해당없음`이 아닐 때만** 한 문장으로 적는다."""

JUDGE_USER = """[원문 → 번역문]
{pairs}

아래 JSON 형식으로만 답하라. 다른 말은 붙이지 마라.

{{"scores": [{{"id": "<id>", "instruction": <1~10>, "hallucination": <1~10>, "quality": <1~10>, "compliance": "<정당|부당|해당없음>", "reason": "<한 문장. 없으면 빈 문자열>"}}]}}"""


def build_judge(pairs: list[dict], target_lang: str,
                table: list[dict] | None) -> tuple[str, str]:
    """pairs = [{"id", "source", "translation"}] → (system, user).

    **블라인드다.** 모델명·토큰량·소요를 넘기지 않는다. 넘기면 편향이 돌아오고,
    출력 토큰 수가 모델을 식별하는 지문이 된다.
    """
    axis_table = "\n".join(f"| `{k}` | {v} |" for k, v in JUDGE_AXES.items())
    body = "\n".join(
        f'{p["id"]}\n  원문: {p["source"]}\n  번역: {p["translation"]}' for p in pairs
    )
    return (
        JUDGE_SYSTEM.format(target_lang=target_lang, axis_table=axis_table,
                            regulation_block=regulation_block(table)),
        JUDGE_USER.format(pairs=body),
    )
