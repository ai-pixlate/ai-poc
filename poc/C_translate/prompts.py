"""C. 로컬라이징 번역 — 프롬프트 틀.

번역 프롬프트와 judge 프롬프트를 한곳에 둔다. 모델마다 프롬프트가 다르면
모델 성능이 아니라 프롬프트 차이를 재게 되므로, 4종에 같은 문안을 쓴다.

평가 축은 문서 2.3을 따른다 — 번역 품질 + 도메인 특화(성분·인증 용어 정확도,
규제 표현 적절 대체).
"""

from __future__ import annotations

import json

# ─────────────────────────────────────────────────────────────
# 번역
# ─────────────────────────────────────────────────────────────

TRANSLATE_SYSTEM = """당신은 한국 화장품 상세페이지를 {target_lang}(으)로 현지화하는 번역가다.

원문은 상세페이지 이미지에서 OCR로 추출한 텍스트다. 다음을 지켜라.

1. 뷰티 도메인 용어를 정확히 옮긴다. 성분명·인증명은 해당 시장에서 통용되는 표기를 쓴다.
{rule_2}
3. 브랜드명·제품명은 번역하지 않고 원표기를 유지한다.
4. 상세페이지 문구이므로 길이를 원문과 비슷하게 유지한다. 이미지 위에 얹을 문구라 길어지면 배치가 깨진다.
5. OCR 오탈자로 보이는 부분은 문맥으로 추정해 옮기되, 추정한 항목은 `note`에 남긴다.

{regulation_block}

같은 페이지의 다른 문구를 문맥으로 함께 준다. 번역 대상은 `segments`뿐이다."""

TRANSLATE_USER = """[같은 페이지 전체 문구 — 문맥용, 번역 대상 아님]
{page_context}

[번역 대상]
{segments}

각 세그먼트를 번역해 아래 JSON 형식으로만 답하라. 다른 말은 붙이지 마라.

{{"translations": [{{"id": "<입력 id 그대로>", "translation": "<번역문>", "note": "<추정·대체한 내용이 있으면. 없으면 빈 문자열>"}}]}}"""


# ─────────────────────────────────────────────────────────────
# 프롬프트 variant (PLAN.md 3-2)
#
# 변인은 규칙 2뿐이다. 나머지 문안·규제 표·문맥 전달 방식은 전부 동일하게 두어야
# variant 간 차이를 "지시 설계의 차이"로 읽을 수 있다.
#
# ⚠️ `v0_baseline`의 문안은 **한 글자도 바꾸지 말 것.** 바꾸면 프롬프트 지문이
#    달라져 이미 만든 캐시가 전부 무효화되고 기준선을 다시 결제해야 한다.
# ─────────────────────────────────────────────────────────────

RULE_2: dict[str, str] = {
    "v0_baseline":
        "2. 아래 규제 매핑 표에 있는 표현은 반드시 지정된 대체 표현으로 바꾼다.",

    # 치환 억제 조건을 문장으로 명시한다. 기준선에서 `유지` 30쌍이 0/30이었고
    # 원인은 프롬프트가 "바꿔라"만 말하고 "언제 바꾸지 말라"를 말하지 않은 것이다.
    "v1_exception":
        "2. 아래 규제 매핑 표에 있는 표현은 지정된 대체 표현으로 바꾼다.\n"
        "   단, 아래 세 경우에는 **바꾸지 말고 원문의 뜻을 그대로 옮긴다.**\n"
        "   (1) 효능을 부인하거나 고지하는 문맥 — \"~하지 않습니다\", \"~보장하지 않습니다\",\n"
        "       \"~입증된 바 없습니다\", \"의약품이 아니므로\" 등. 바꾸면 고지 기능이 깨진다.\n"
        "   (2) 인용부호 안의 제3자 발화 — 후기·인터뷰·전문가 코멘트.\n"
        "       바꾸면 그 사람이 하지 않은 말이 된다.\n"
        "   (3) 제품명·라인명의 일부 — \"(제품명)\" 표기가 없어도 제품을 가리키는\n"
        "       이름이면 유지한다.",

    # 열거 대신 원리. `v1_exception`이 **열거한 3유형은 30/30, 열거하지 않은 3유형은
    # 1/19**였다 — 가르친 것만 했다. 실서비스에는 우리가 열거하지 않은 문맥이 계속
    # 나오므로 열거식은 답이 될 수 없다.
    #
    # ⚠️ 예시는 **v1이 이미 가르친 유형(부인·인용)에서만** 든다. 새로 추가한
    #    G 법령·H UI 라벨·I 수상 유형을 암시하면 또 열거가 되어 검증이 무의미해진다.
    "v6_principle":
        "2. 아래 규제 매핑 표는 **브랜드가 그 효능을 스스로 주장하는 자리**에만 적용한다.\n"
        "   바꾸기 전에 스스로 물어라 — **이 표현을 바꾸면 원문이 가리키던 대상이\n"
        "   달라지거나 사실관계가 틀어지는가?** 그렇다면 바꾸지 말고 원문의 뜻을\n"
        "   그대로 옮긴다.\n"
        "   예) \"미백 효과를 보장하지 않습니다\" — 효능을 부인하는 문장이므로\n"
        "       바꾸면 고지 기능이 깨진다.\n"
        "   예) 후기 인용 \"기미가 옅어졌어요\" — 제3자의 발화이므로 바꾸면\n"
        "       그 사람이 하지 않은 말이 된다.",
}


def regulation_block(table: list[dict] | None) -> str:
    if not table:
        return ("[규제 매핑 표]\n"
                "_미제공_ — 규제 표현 대체 축은 채점 대상에서 제외된다.")
    lines = ["[규제 매핑 표] 아래 표현은 반드시 대체하라."]
    for row in table:
        lines.append(f"  - {row.get('금지표현')} → {row.get('대체표현')}"
                     + (f"  ({row['근거']})" if row.get("근거") else ""))
    return "\n".join(lines)


def build_translate(doc: dict, target_lang: str, table: list[dict] | None,
                    variant: str = "v0_baseline") -> tuple[str, str]:
    """문서 1건 → (system, user)."""
    if variant not in RULE_2:
        raise SystemExit(f"variant `{variant}` 미정의 — prompts.RULE_2에 추가할 것")
    segments = [{"id": s["id"], "text": s["manual_fix"] or s["source"]} for s in doc["segments"]]
    return (
        TRANSLATE_SYSTEM.format(target_lang=target_lang, rule_2=RULE_2[variant],
                                regulation_block=regulation_block(table)),
        TRANSLATE_USER.format(
            page_context=" / ".join(doc["page_text"]),
            segments=json.dumps(segments, ensure_ascii=False, indent=1),
        ),
    )


